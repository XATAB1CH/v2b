package services

type DraftEmailParams struct {
	Text      string
	Lang      string
	Tone      string
	Recipient string
	Sender    string
}

func BuildDraftEmailPrompt(p DraftEmailParams) string {
	// Улучшенный промпт: превращаем “сырой” текст в письмо,
	// добавляем структуру, тему, CTA, placeholders.
	tone := p.Tone
	if tone == "" {
		tone = "neutral"
	}
	lang := p.Lang
	if lang == "" {
		lang = "ru"
	}

	recipient := p.Recipient
	if recipient == "" {
		recipient = "[Имя получателя]"
	}
	sender := p.Sender
	if sender == "" {
		sender = "[Ваше имя]"
	}

	return "" +
		"Ты — помощник по деловой переписке.\n" +
		"Задача: по исходному наброску ниже составь готовое деловое письмо.\n\n" +
		"Требования:\n" +
		"- Язык: " + lang + "\n" +
		"- Тон: " + tone + " (деловой, вежливый, без лишней воды)\n" +
		"- Письмо должно быть структурировано: Тема письма (Subject), приветствие, основной текст, чёткий следующий шаг/CTA, завершение, подпись.\n" +
		"- Если не хватает данных (даты, суммы, контакта, адресата, названия компании) — НЕ задавай вопросы, а вставляй плейсхолдеры в квадратных скобках.\n" +
		"- Не выдумывай факты: только аккуратно переформулируй и упорядочи.\n" +
		"- Максимум 140–220 слов, если исходный текст короткий.\n\n" +
		"Адресат: " + recipient + "\n" +
		"Отправитель: " + sender + "\n\n" +
		"Исходный текст:\n" +
		p.Text + "\n\n" +
		"Верни только готовое письмо (включая строку Subject: ...), без пояснений."
}
